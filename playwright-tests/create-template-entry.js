'use strict';

const path = require('path');
const { randomBytes, randomUUID } = require('crypto');
const { chromium } = require('@playwright/test');
const {
  enableArtifactOverlayOnContext,
  enableArtifactOverlayOnPage,
  updateArtifactOverlay,
} = require('./helpers/artifactOverlay');

const SEL = {
  username: '#txtUsername',
  password: '#txtPassword',
  loginBtn: '#btnLogin',
  unlockBtn: '#btnUnlock',
  homeReady: '#divAppButton',
};

const CREATE_TEMPLATE_ROUTES = [
  '/Create-Template',
  '/create-template',
  '/Design-Template',
  '/design-template',
];

function boolEnv(value, defaultValue) {
  if (value === undefined || value === null || value === '') return defaultValue;
  return String(value).toLowerCase() === 'true';
}

function randomName() {
  const stamp = (typeof randomUUID === 'function'
    ? randomUUID().replace(/-/g, '')
    : randomBytes(16).toString('hex')
  ).toUpperCase().slice(0, 16);
  return `AUTO-TEMPLATE-${stamp}`;
}

async function login(page, { loginUrl, username, password }) {
  const base = new URL(loginUrl || 'https://ipdev.quickflow.in/login').origin;
  await page.goto(base, { waitUntil: 'load', timeout: 30000 });
  await page.waitForSelector(SEL.username, { timeout: 30000 });

  await page.fill(SEL.username, username);
  await page.fill(SEL.password, password);
  await page.click(SEL.loginBtn);
  await page.waitForTimeout(800);

  const unlockVisible = await page.locator(SEL.unlockBtn).isVisible().catch(() => false);
  if (unlockVisible) {
    await page.click(SEL.unlockBtn);
    await page.waitForTimeout(800);
  }

  await page.waitForSelector(SEL.homeReady, { timeout: 30000 });
}

async function findCreateTemplateRoute(page, baseURL) {
  const navRoute = await page.evaluate(() => {
    const links = Array.from(document.querySelectorAll('a[href]')).map((a) => ({
      href: String(a.getAttribute('href') || '').trim(),
      text: String(a.textContent || '').trim().toLowerCase(),
    }));

    const hit = links.find((link) => {
      const probe = `${link.href} ${link.text}`;
      return probe.includes('create template') || probe.includes('design template');
    });

    return hit?.href || '';
  }).catch(() => '');

  if (navRoute) {
    return navRoute.startsWith('/') ? navRoute : `/${navRoute}`;
  }

  for (const route of CREATE_TEMPLATE_ROUTES) {
    try {
      const resp = await page.goto(`${baseURL}${route}`, { waitUntil: 'domcontentloaded', timeout: 15000 });
      const status = resp?.status?.() || 0;
      if (status >= 200 && status < 400) {
        return route;
      }
    } catch {
      continue;
    }
  }

  throw new Error('Create Template route not found');
}

async function fillTemplateInputs(page, requestedName) {
  const templateName = requestedName || randomName();

  const filled = await page.evaluate((name) => {
    const out = [];
    const container = document.querySelector('.page-content, .card-body, form, main') || document.body;

    const textInputs = Array.from(container.querySelectorAll('input:not([type="hidden"]):not([type="button"]):not([type="submit"]):not([type="checkbox"]):not([type="radio"]):not([disabled]), textarea:not([disabled])'));

    for (const input of textInputs) {
      const probe = `${input.id || ''} ${input.name || ''} ${input.placeholder || ''}`.toLowerCase();
      let value = '';
      if (/name|title|template/.test(probe)) value = name;
      else if (/desc|remark|comment|note/.test(probe)) value = `Generated by automation: ${name}`;
      else if (input.tagName.toLowerCase() === 'textarea') value = `Generated by automation: ${name}`;
      else value = name;

      input.focus();
      input.value = value;
      input.dispatchEvent(new Event('input', { bubbles: true }));
      input.dispatchEvent(new Event('change', { bubbles: true }));
      input.dispatchEvent(new Event('blur', { bubbles: true }));
      if (window.$) {
        window.$(input).trigger('input');
        window.$(input).trigger('change');
        window.$(input).trigger('blur');
      }

      out.push({ field: input.id || input.name || 'input', value });
    }

    const selects = Array.from(container.querySelectorAll('select:not([disabled])'));
    for (const sel of selects) {
      if (sel.value && sel.value !== '-1' && sel.value !== '0' && sel.value !== '') continue;
      const option = Array.from(sel.options).find((o) => o.value && o.value !== '-1' && o.value !== '0');
      if (!option) continue;

      sel.value = option.value;
      sel.dispatchEvent(new Event('change', { bubbles: true }));
      sel.dispatchEvent(new Event('blur', { bubbles: true }));
      if (window.$) {
        window.$(sel).trigger('change');
        window.$(sel).trigger('blur');
      }
      out.push({ field: sel.id || sel.name || 'select', value: (option.textContent || '').trim() });
    }

    return out;
  }, templateName);

  return { templateName, filled };
}

async function saveEntry(page) {
  const candidates = [
    page.locator('button:visible:not([disabled])', { hasText: /^\s*Save\s*as\s*new\s*$/i }).first(),
    page.locator('button:visible:not([disabled])', { hasText: /^\s*Save\s*$/i }).first(),
    page.locator('button:visible:not([disabled])', { hasText: /save/i }).first(),
    page.locator('#btnSave:visible').first(),
    page.locator('#btnSubmit:visible').first(),
  ];

  let clicked = false;
  for (const btn of candidates) {
    const visible = await btn.isVisible().catch(() => false);
    if (!visible) continue;
    await btn.click({ timeout: 5000, force: true }).catch(() => {});
    clicked = true;
    break;
  }

  if (!clicked) throw new Error('Save button not found on Create Template page');

  await page.waitForTimeout(1500);

  for (let i = 0; i < 3; i++) {
    const confirmBtn = page.locator('.swal2-confirm:visible:not([disabled])').first();
    if (await confirmBtn.isVisible().catch(() => false)) {
      await confirmBtn.click({ timeout: 3000, force: true }).catch(() => {});
      await page.waitForTimeout(350);
    }

    const modalBtn = page.locator('.modal.show button:visible:not([disabled])', {
      hasText: /ok|yes|confirm|submit|save/i,
    }).first();
    if (await modalBtn.isVisible().catch(() => false)) {
      await modalBtn.click({ timeout: 3000, force: true }).catch(() => {});
      await page.waitForTimeout(350);
    }
  }

  const message = await page.evaluate(() => {
    const nodes = document.querySelectorAll('.swal2-title, .swal2-html-container, .toast-message, .Toastify__toast, .alert-success');
    for (const node of nodes) {
      const text = (node.textContent || '').trim();
      if (text) return text;
    }
    return 'Save attempted';
  }).catch(() => 'Save attempted');

  return message;
}

async function run() {
  const origLog = console.log;
  const origWarn = console.warn;
  console.log = (...args) => process.stderr.write(args.join(' ') + '\n');
  console.warn = (...args) => process.stderr.write(args.join(' ') + '\n');

  const cfg = {
    loginUrl: process.env.QT_URL || 'https://ipdev.quickflow.in/login',
    username: process.env.QT_USER || 'dhruvi',
    password: process.env.QT_PASS || '',
    headless: boolEnv(process.env.QT_HEADLESS, false),
    recordVideo: boolEnv(process.env.QT_RECORD_VIDEO, true),
    templateName: process.env.QT_TEMPLATE_NAME || '',
  };

  let browser;
  let context;
  try {
    browser = await chromium.launch({ headless: cfg.headless });
    const contextOptions = {
      viewport: { width: 1366, height: 900 },
    };
    if (cfg.recordVideo) {
      contextOptions.recordVideo = {
        dir: 'test-reports',
        size: { width: 1280, height: 720 },
      };
    }
    context = await browser.newContext(contextOptions);
    await enableArtifactOverlayOnContext(context);
    const page = await context.newPage();
    await enableArtifactOverlayOnPage(page);
    await updateArtifactOverlay(page, {
      operation: 'create-template-entry',
      status: 'running',
      step: 'login',
    });

    await login(page, cfg);
    const baseURL = new URL(cfg.loginUrl).origin;
    const route = await findCreateTemplateRoute(page, baseURL);

    await page.goto(`${baseURL}${route}`, { waitUntil: 'domcontentloaded', timeout: 30000 });
    await page.waitForLoadState('networkidle', { timeout: 15000 }).catch(() => {});
    await page.waitForTimeout(1200);
    await updateArtifactOverlay(page, {
      operation: 'create-template-entry',
      status: 'running',
      step: 'fill-and-save',
    });

    const { templateName, filled } = await fillTemplateInputs(page, cfg.templateName);
    await updateArtifactOverlay(page, {
      operation: 'create-template-entry',
      status: 'running',
      step: 'save-entry',
    });
    const saveMessage = await saveEntry(page);
    await updateArtifactOverlay(page, {
      operation: 'create-template-entry',
      status: 'completed',
      step: 'done',
    });

    const result = {
      executedAt: new Date().toISOString(),
      route,
      templateName,
      fieldsFilled: filled,
      saveMessage,
      status: 'completed',
    };

    console.log = origLog;
    console.warn = origWarn;
    process.stdout.write(JSON.stringify(result));
  } finally {
    console.log = origLog;
    console.warn = origWarn;
    if (context) await context.close().catch(() => {});
    if (browser) await browser.close().catch(() => {});
  }
}

run().catch((error) => {
  const message = error?.stack || error?.message || String(error) || 'Create template entry failed';
  process.stderr.write(message);
  process.exit(1);
});
